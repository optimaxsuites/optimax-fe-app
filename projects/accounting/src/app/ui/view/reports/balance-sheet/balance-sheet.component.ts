import { Component, OnDestroy, OnInit } from '@angular/core';
import { combineLatest, Subject } from 'rxjs';
import { takeUntil } from 'rxjs/operators';

import { AccountingFormatService } from '../../../../core/services/accounting-format.service';
import { AccountingDiagnostics, AccountingService } from '../../../../core/services/accounting.service';
import {
  AccountBalanceDTO,
  AccountDTO,
  AccountingTransactionDTO,
  BalanceSheetReportDTO,
  JournalEntryDTO,
  JournalEntryLineDTO,
  SavedReportSnapshotDTO,
} from '../report.dto';

interface ReportComment {
  user: string;
  text: string;
  date: Date;
}

@Component({
  selector: 'app-balance-sheet',
  templateUrl: './balance-sheet.component.html',
  styleUrls: ['./balance-sheet.component.scss']
})
export class BalanceSheetComponent implements OnInit, OnDestroy {
  readonly currentYear = new Date().getFullYear();
  readonly years = [this.currentYear - 1, this.currentYear, this.currentYear + 1];
  readonly months = Array.from({ length: 12 }, (_, month) => ({
    value: month,
    label: new Date(2025, month, 1).toLocaleString('en-US', { month: 'long' }),
  }));

  selectedYear = this.currentYear;
  selectedMonth = new Date().getMonth();

  report: BalanceSheetReportDTO | null = null;
  loading = true;
  errorMessage = '';
  statusMessage = '';
  diagnostics: AccountingDiagnostics | null = null;

  accounts: AccountDTO[] = [];
  transactions: AccountingTransactionDTO[] = [];
  journalEntries: JournalEntryDTO[] = [];
  journalLines: JournalEntryLineDTO[] = [];

  userComments: ReportComment[] = [];
  newComment = '';

  isSavedReportsOpen = false;
  searchFilter = '';
  savedReports: SavedReportSnapshotDTO[] = [];

  private readonly destroy$ = new Subject<void>();

  constructor(
    private readonly accountingService: AccountingService,
    readonly fmt: AccountingFormatService,
  ) {}

  ngOnInit(): void {
    this.loadReferenceData();
    this.loadSavedReports();
    this.diagnostics = this.accountingService.getDiagnostics();
    this.loadReport();
  }

  ngOnDestroy(): void {
    this.destroy$.next();
    this.destroy$.complete();
  }

  get hasReportData(): boolean {
    return !!this.report && (this.report.totalAssets > 0 || this.report.totalLiabilities > 0 || this.report.totalEquity > 0);
  }

  get reportDate(): Date | null {
    return this.report ? new Date(this.report.reportDate) : null;
  }

  get totalAssets(): number {
    return this.report?.totalAssets ?? 0;
  }

  get totalLiabilities(): number {
    return this.report?.totalLiabilities ?? 0;
  }

  get totalEquity(): number {
    return this.report?.totalEquity ?? 0;
  }

  get equationDifference(): number {
    return this.totalAssets - (this.totalLiabilities + this.totalEquity);
  }

  get isBalanced(): boolean {
    return Math.abs(this.equationDifference) < 0.01;
  }

  get filteredSavedReports(): SavedReportSnapshotDTO[] {
    const query = this.searchFilter.trim().toLowerCase();
    if (!query) {
      return this.savedReports;
    }

    return this.savedReports.filter((report) =>
      report.reportLabel.toLowerCase().includes(query) ||
      report.periodLabel.toLowerCase().includes(query)
    );
  }

  get metadataTransactions(): Array<{
    id: string;
    reference: string;
    sourceModule: string;
    status: string;
    date: string;
    description: string;
  }> {
    if (!this.report) {
      return [];
    }

    const journalEntryMap = new Map(this.journalEntries.map((entry) => [entry.id, entry]));

    return this.report.reportContext.includedTransactionIds
      .map((transactionId) => this.transactions.find((transaction) => String(transaction.id) === String(transactionId)))
      .filter((transaction): transaction is AccountingTransactionDTO => !!transaction)
      .map((transaction: AccountingTransactionDTO) => ({
        id: String(transaction.id),
        reference: transaction.reference ?? transaction.transactionReference ?? String(transaction.id),
        sourceModule: String(transaction.sourceModule),
        status: String(journalEntryMap.get(transaction.journalEntryId ?? '')?.status ?? transaction.reviewStatus ?? 'UNKNOWN'),
        date: transaction.transactionDate,
        description: transaction.description,
      }));
  }

  get groupedMetadata(): Array<{ label: string; value: string }> {
    if (!this.report) {
      return [];
    }

    const metadata = this.report.reportContext;
    return [
      { label: 'Generated At', value: this.fmt.formatDate(metadata.generatedAt, 'full') },
      { label: 'Generated By', value: this.formatGeneratedBy(metadata.generatedBy) },
      { label: 'Period Start', value: this.fmt.formatDate(metadata.periodStart, 'long') },
      { label: 'Period End', value: this.fmt.formatDate(metadata.periodEnd, 'long') },
      { label: 'Source Modules', value: metadata.sourceModules.join(', ') || 'N/A' },
      { label: 'Included Transactions', value: `${metadata.includedTransactionIds.length}` },
    ];
  }

  get balanceSummary(): Array<{ label: string; value: number; tone: 'neutral' | 'good' | 'warning' }> {
    return [
      { label: 'Total Assets', value: this.totalAssets, tone: 'neutral' },
      { label: 'Total Liabilities', value: this.totalLiabilities, tone: 'warning' },
      { label: 'Total Equity', value: this.totalEquity, tone: 'good' },
      { label: 'Equation Difference', value: this.equationDifference, tone: this.isBalanced ? 'good' : 'warning' },
    ];
  }

  onPeriodChange(): void {
    this.loadReport();
  }

  saveReport(): void {
    if (!this.hasReportData) {
      return;
    }

    this.statusMessage = 'Snapshot creation is not exposed by the backend yet. This panel only shows snapshots returned by /reports/saved-snapshots.';
  }

  openSavedReport(snapshot: SavedReportSnapshotDTO): void {
    const reportDate = new Date(snapshot.periodEnd);
    this.selectedYear = reportDate.getFullYear();
    this.selectedMonth = reportDate.getMonth();
    this.accountingService.setPeriod(new Date(snapshot.periodStart));
    this.loading = true;
    this.errorMessage = '';
    this.statusMessage = '';

    this.accountingService.getBalanceSheetReport({
      periodStart: snapshot.periodStart,
      periodEnd: snapshot.periodEnd,
      reportPeriodType: snapshot.periodType,
    })
      .pipe(takeUntil(this.destroy$))
      .subscribe({
        next: (report: BalanceSheetReportDTO) => {
          this.report = report;
          this.loading = false;
          this.isSavedReportsOpen = false;
          this.statusMessage = `Loaded backend snapshot for ${snapshot.periodLabel}.`;
        },
        error: () => {
          this.loading = false;
          this.errorMessage = `We could not reload the saved balance sheet for ${snapshot.periodLabel}.`;
        },
      });
  }

  postComment(): void {
    if (!this.newComment.trim()) {
      return;
    }

    this.userComments = [
      {
        user: 'Current User',
        text: this.newComment.trim(),
        date: new Date(),
      },
      ...this.userComments,
    ];
    this.newComment = '';
  }

  private formatGeneratedBy(generatedBy: BalanceSheetReportDTO['reportContext']['generatedBy']): string {
    if (typeof generatedBy === 'string' || typeof generatedBy === 'number') {
      return String(generatedBy);
    }

    return generatedBy.fullname || generatedBy.username || generatedBy.email || 'System';
  }

  toggleSavedReports(): void {
    this.isSavedReportsOpen = !this.isSavedReportsOpen;
  }

  trackByAccount(_: number, item: AccountBalanceDTO): string {
    return String(item.accountId ?? item.accountCode);
  }

  private loadReferenceData(): void {
    combineLatest([
      this.accountingService.getReportAccounts(),
      this.accountingService.getAccountingTransactions(),
      this.accountingService.getJournalEntries(),
      this.accountingService.getJournalEntryLines(),
    ])
      .pipe(takeUntil(this.destroy$))
      .subscribe(([accounts, transactions, journalEntries, journalLines]) => {
        this.accounts = accounts;
        this.transactions = transactions;
        this.journalEntries = journalEntries;
        this.journalLines = journalLines;
      });
  }

  private loadSavedReports(): void {
    this.accountingService.getSavedReportSnapshots(1, 50)
      .pipe(takeUntil(this.destroy$))
      .subscribe({
        next: (result) => {
          this.savedReports = result.content.filter((snapshot) => snapshot.reportType === 'balance-sheet');
        },
        error: () => {
          this.savedReports = [];
        },
      });
  }

  private loadReport(): void {
    this.loading = true;
    this.errorMessage = '';
    this.statusMessage = '';
    this.diagnostics = this.accountingService.getDiagnostics();

    this.accountingService.setPeriod(new Date(this.selectedYear, this.selectedMonth, 1));
    this.accountingService.getBalanceSheetReport()
      .pipe(takeUntil(this.destroy$))
      .subscribe({
        next: (report: BalanceSheetReportDTO) => {
          this.report = report;
          this.loading = false;
          this.diagnostics = this.accountingService.getDiagnostics();
        },
        error: (error) => {
          this.diagnostics = this.accountingService.getDiagnostics();
          if (!this.diagnostics?.entityId) {
            this.errorMessage = '✗ Missing entity ID. Please confirm your login response includes entityId and that it is stored in localStorage/sessionStorage.';
          } else {
            this.errorMessage = `✗ We could not load the balance sheet for ${this.periodLabel}. Check console logs for details.`;
          }
          console.error('[BalanceSheet] loadReport failed:', error);
          this.loading = false;
        },
      });
  }

  get periodLabel(): string {
    return `${this.months[this.selectedMonth]?.label ?? ''} ${this.selectedYear}`;
  }
}
