import { Component, Input } from '@angular/core';

import { ReportContextDTO } from './report.dto';

@Component({
  selector: 'app-report-context',
  template: `
    <section class="report-context-section" *ngIf="context">
      <article class="detail-card">
        <div class="detail-header">
          <p class="eyebrow">DTO-Derived Statement Context</p>
          <h3>Report Details</h3>
        </div>
        <dl class="metadata-list compact-inline">
          <div><dt>Generated At</dt><dd>{{ toDatePipeValue(context.generatedAt) | date:'medium' }}</dd></div>
          <div><dt>Generated By</dt><dd>{{ generatedByLabel }}</dd></div>
          <div><dt>Period Start</dt><dd>{{ toDatePipeValue(context.periodStart) | date:'longDate' }}</dd></div>
          <div><dt>Period End</dt><dd>{{ toDatePipeValue(context.periodEnd) | date:'longDate' }}</dd></div>
          <div><dt>Entity</dt><dd>{{ context.entityName }}</dd></div>
          <div><dt>Currency</dt><dd>{{ context.currencyCode }}</dd></div>
          <div><dt>Report Version</dt><dd>{{ context.reportVersion }}</dd></div>
          <div><dt>Compliance Framework</dt><dd>{{ context.complianceFramework }}</dd></div>
          <div><dt>Source Modules</dt><dd>{{ context.sourceModules.join(', ') }}</dd></div>
          <div *ngIf="context.includedTransactionIds.length">
            <dt>Included Transactions</dt>
            <dd>{{ context.includedTransactionIds.length }}</dd>
          </div>
        </dl>
      </article>
    </section>
  `,
})
export class ReportContextComponent {
  @Input() context: ReportContextDTO | null = null;

  get generatedByLabel(): string {
    if (!this.context) {
      return '';
    }

    const generatedBy = this.context.generatedBy;
    if (typeof generatedBy === 'string' || typeof generatedBy === 'number') {
      return String(generatedBy);
    }

    return generatedBy.fullname || generatedBy.username || generatedBy.email || 'System';
  }

  toDatePipeValue(value: string | number[]): string | Date {
    if (Array.isArray(value)) {
      const [year, month = 1, day = 1, hour = 0, minute = 0, second = 0, nanos = 0] = value;
      return new Date(year, month - 1, day, hour, minute, second, Math.floor(nanos / 1_000_000));
    }

    return value;
  }
}
